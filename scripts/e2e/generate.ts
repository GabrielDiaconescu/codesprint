import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { stringify } from 'yaml';

import { loadContent, type LoadedCourse } from '../content/load';
import { fixtureSql, lessonAfterModuleOne, moduleOneLessons, pinnedChallenge } from './fixtures';
import { answerQuestion, attemptFirstQuestion, playLesson, waitFor, type Command } from './steps';

/**
 * Writes the content-derived half of the E2E suite into `e2e/generated/` (gitignored).
 *
 * The hand-written flows in `e2e/flows/` say WHAT is tested; these subflows supply the
 * answers, derived from the content on every run so they cannot drift from it (see steps.ts).
 */

export const GENERATED_DIR = join(process.cwd(), 'e2e', 'generated');

const flow = (commands: Command[]): string =>
  `# GENERATED by scripts/e2e/generate.ts from content/ — do not edit.\n` +
  `appId: \${APP_ID}\n---\n${stringify(commands)}`;

/**
 * Every generated file, by name. Pure, so a test can check that each `runFlow` in the
 * hand-written flows points at a file that will exist.
 *
 * - `play-lesson-N.yaml`   module 1, lesson N, every answer right; ends on the completion screen
 * - `miss-lesson-N.yaml`   the same lesson, every answer plausibly wrong; stops on the LAST
 *                          question's feedback, where the caller asserts what it cost
 * - `play-challenge.yaml`  the pinned Daily Challenge, right; ends on its results screen
 * - `attempt-next-lesson.yaml`  module 2, lesson 1, up to pressing Check on its first question
 * - `fixtures.sql`         the database state the flows start from (fixtures.ts)
 */
export const generatedFiles = (courses: LoadedCourse[]): Record<string, string> => {
  const files: Record<string, string> = {};

  moduleOneLessons(courses).forEach((lesson, index) => {
    files[`play-lesson-${index + 1}.yaml`] = flow(playLesson(lesson));
    files[`miss-lesson-${index + 1}.yaml`] = flow(
      playLesson(lesson, { mode: 'wrong', stopAtLastFeedback: true }),
    );
  });

  files['play-challenge.yaml'] = flow([
    ...pinnedChallenge(courses).flatMap((question) => answerQuestion(question, 'correct')),
    waitFor('challenge-done'),
  ]);

  files['attempt-next-lesson.yaml'] = flow(attemptFirstQuestion(lessonAfterModuleOne(courses)));

  files['fixtures.sql'] = fixtureSql(courses);

  return files;
};

export const loadCourses = (): LoadedCourse[] => {
  const { courses, issues } = loadContent();
  if (issues.length > 0) {
    throw new Error(
      `content does not load — run npm run content:validate\n` +
        issues.map((issue) => `  ${issue.file}: ${issue.message}`).join('\n'),
    );
  }
  return courses;
};

export const writeGenerated = (courses: LoadedCourse[] = loadCourses()): string[] => {
  // Emptied first: a lesson removed from the content must not leave a stale flow behind.
  rmSync(GENERATED_DIR, { recursive: true, force: true });
  mkdirSync(GENERATED_DIR, { recursive: true });

  const files = generatedFiles(courses);
  for (const [name, body] of Object.entries(files)) {
    writeFileSync(join(GENERATED_DIR, name), body, 'utf8');
  }
  return Object.keys(files);
};

if (process.argv[1]?.includes('generate')) {
  const names = writeGenerated();
  console.log(`Wrote ${names.length} files to e2e/generated/`);
}
