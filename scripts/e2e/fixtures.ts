import type { LoadedCourse } from '../content/load';
import { DEV_USERS, type DevUser } from '../content/seed';
import type { ContentQuestion, LessonFile } from '../../src/lib/content/schema';

/**
 * State the E2E flows start from, on top of a freshly reset LOCAL database (SPEC §52, §53).
 *
 * Only what a flow cannot reach quickly through the app itself, and always through the same
 * functions the app calls: the free account's first lessons are finished by replaying
 * `submit_answer` and `complete_lesson`, not by inserting progress rows, so the counters, the
 * XP ledger and the streak are exactly what a learner would have after doing it by hand.
 *
 * Never run against staging or production. `run.ts` applies this through `docker exec` into
 * the local Supabase container, which is the only database it can reach.
 */

/** The free account has finished this many lessons, so the lives grace period is over. */
export const FREE_ACCOUNT_FINISHED_LESSONS = 3;

const devUser = (email: string): DevUser => {
  const user = DEV_USERS.find((u) => u.email === email);
  if (!user) throw new Error(`no seeded dev account ${email}`);
  return user;
};

export const FREE_ACCOUNT = devUser('free@codesprint.test');
export const PREMIUM_ACCOUNT = devUser('premium@codesprint.test');

const firstCourse = (courses: LoadedCourse[]): LoadedCourse => {
  const course = courses[0];
  if (!course) throw new Error('no course content');
  return course;
};

/** Module 1's lessons in order: reviewed, free, and between them every question type. */
export const moduleOneLessons = (courses: LoadedCourse[]): LessonFile[] => {
  const moduleOne = firstCourse(courses).modules[0];
  if (!moduleOne) throw new Error('no module 1');
  return moduleOne.lessons.map((lesson) => lesson.data);
};

/** What the free account meets after module 1: module 2's first lesson. */
export const lessonAfterModuleOne = (courses: LoadedCourse[]): LessonFile => {
  const lesson = firstCourse(courses).modules[1]?.lessons[0];
  if (!lesson) throw new Error('no module 2, lesson 1');
  return lesson.data;
};

/**
 * Three questions pinned as the Daily Challenge for every date near today, so the flow knows
 * the answers. Taken from module 1 — always free — and only those marked challenge-eligible.
 */
export const pinnedChallenge = (courses: LoadedCourse[]): ContentQuestion[] => {
  const questions = moduleOneLessons(courses)
    .flatMap((lesson) => lesson.blocks)
    .flatMap((block) => (block.type === 'question' ? [block.question] : []))
    .filter((question) => question.is_challenge_eligible !== false)
    .slice(0, 3);

  if (questions.length < 3) throw new Error('module 1 has fewer than 3 challenge questions');
  return questions;
};

const literal = (value: string): string => `'${value.replace(/'/g, "''")}'`;

const uuidArray = (ids: string[]): string => `array[${ids.map(literal).join(', ')}]::uuid[]`;

export const fixtureSql = (courses: LoadedCourse[]): string => {
  const finished = moduleOneLessons(courses).slice(0, FREE_ACCOUNT_FINISHED_LESSONS);
  const challenge = pinnedChallenge(courses);
  const signedIn = [FREE_ACCOUNT, PREMIUM_ACCOUNT];

  return `-- GENERATED by scripts/e2e/fixtures.ts for the E2E run. LOCAL DATABASE ONLY.
begin;

-- The accounts the flows sign in with have already been through onboarding, so a flow that
-- signs in lands on Home. Onboarding itself is covered by its own flow, as a new guest.
update public.profiles
set experience_level = 'complete_beginner',
    motivation = 'personal',
    daily_goal_minutes = 5,
    onboarding_completed_at = now()
where id in (${signedIn.map((u) => literal(u.id)).join(', ')});

-- The free account finishes its first ${FREE_ACCOUNT_FINISHED_LESSONS} lessons through the real functions, as itself.
do $$
declare
  r record;
begin
  perform set_config(
    'request.jwt.claims',
    json_build_object('sub', ${literal(FREE_ACCOUNT.id)}, 'role', 'authenticated')::text,
    true
  );

  for r in
    select q.id, k.answer
    from public.questions q
    join public.question_answer_keys k on k.question_id = q.id
    join public.lessons l on l.id = q.lesson_id
    where q.lesson_id = any (${uuidArray(finished.map((l) => l.id))})
    order by l.order_index, q.order_index
  loop
    perform public.submit_answer(r.id, r.answer, 'lesson');
  end loop;

${finished.map((l) => `  perform public.complete_lesson(${literal(l.id)});`).join('\n')}
end;
$$;

-- The Daily Challenge, pinned for yesterday, today and tomorrow: whichever the emulator's
-- timezone makes "today" for the learner, the flow knows the three questions.
insert into public.daily_challenges (challenge_date, question_ids, bonus_xp)
select d::date, ${uuidArray(challenge.map((q) => q.id))}, 25
from generate_series(current_date - 1, current_date + 1, interval '1 day') as d
on conflict (challenge_date) do update set question_ids = excluded.question_ids;

commit;
`;
};
