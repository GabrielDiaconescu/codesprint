import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Writes `web/licenses.html`: every production dependency, its licence, and its licence text
 * (SPEC §29 — "legal: … licenses").
 *
 * Most of these licences (MIT, ISC, BSD, Apache) ask for their notice to travel with every copy
 * of the software, and an app is a copy. Listing the whole production tree is more than is
 * strictly bundled — build tools such as @sentry/cli are in it — but an extra attribution costs
 * nothing, and a missing one is a licence breach.
 *
 * Run after changing dependencies: `npm run legal:licenses`.
 */

interface NpmNode {
  version?: string;
  path?: string;
  license?: string | { type?: string };
  dependencies?: Record<string, NpmNode>;
}

interface Entry {
  name: string;
  version: string;
  license: string;
  text: string | null;
}

const OUTPUT = join(process.cwd(), 'web', 'licenses.html');
const LICENSE_FILE = /^(licen[sc]e|copying)(\.(md|txt|markdown))?$/i;

const escapeHtml = (value: string): string =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** The licence as declared — including the old `licenses: [{ type }]` form some packages use. */
const declaredLicense = (node: NpmNode): string => {
  if (typeof node.license === 'string') return node.license;
  if (node.license?.type) return node.license.type;
  if (node.path) {
    try {
      const manifest = JSON.parse(readFileSync(join(node.path, 'package.json'), 'utf8')) as {
        licenses?: { type?: string }[];
      };
      const types = (manifest.licenses ?? []).map((l) => l.type).filter(Boolean);
      if (types.length > 0) return types.join(' OR ');
    } catch {
      // Unreadable manifest: fall through to "not declared".
    }
  }
  return 'Not declared';
};

const licenseText = (path: string | undefined): string | null => {
  if (!path || !existsSync(path)) return null;
  const file = readdirSync(path).find((name) => LICENSE_FILE.test(name));
  if (!file) return null;
  // Normalised: some packages ship CRLF, which would make the page differ on every run.
  return readFileSync(join(path, file), 'utf8').replace(/\r\n?/g, '\n').trim();
};

export const collectEntries = (tree: NpmNode): Entry[] => {
  const seen = new Map<string, Entry>();

  const walk = (deps: Record<string, NpmNode> | undefined) => {
    for (const [name, node] of Object.entries(deps ?? {})) {
      if (!node.version) continue;
      const key = `${name}@${node.version}`;
      if (seen.has(key)) continue;
      seen.set(key, {
        name,
        version: node.version,
        license: declaredLicense(node),
        text: licenseText(node.path),
      });
      walk(node.dependencies);
    }
  };

  walk(tree.dependencies);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
};

export const renderLicensesPage = (entries: Entry[]): string => {
  const items = entries
    .map(
      (entry) => `      <details>
        <summary><strong>${escapeHtml(entry.name)}</strong> ${escapeHtml(entry.version)} — ${escapeHtml(entry.license)}</summary>
        <pre>${escapeHtml(entry.text ?? 'No licence file was published with this package; its declared licence is above.')}</pre>
      </details>`,
    )
    .join('\n');

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>CodeSprint — Open-source licences</title>
    <meta name="description" content="The open-source software CodeSprint is built with." />
    <link rel="stylesheet" href="style.css" />
    <style>
      details { border-bottom: 1px solid var(--border); padding: 0.5rem 0; }
      pre { white-space: pre-wrap; font-size: 0.8rem; color: var(--muted); }
    </style>
  </head>
  <body>
    <main>
      <header>
        <nav aria-label="Pages">
          <a href="index.html">Support</a>
          <a href="privacy.html">Privacy</a>
          <a href="terms.html">Terms</a>
          <a href="delete-account.html">Delete your account</a>
        </nav>
      </header>

      <h1>Open-source licences</h1>
      <p class="meta">
        CodeSprint is built with ${entries.length} open-source packages. Thank you to everyone who
        made them. Generated by <code>npm run legal:licenses</code>.
      </p>

${items}
    </main>
  </body>
</html>
`;
};

if (process.argv[1]?.includes('licenses')) {
  // A fixed command, no user input; one string so it runs the same through every shell.
  const json = execSync('npm ls --omit=dev --all --json --long', {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  });
  const entries = collectEntries(JSON.parse(json) as NpmNode);
  writeFileSync(OUTPUT, renderLicensesPage(entries), 'utf8');
  console.log(`Wrote web/licenses.html — ${entries.length} packages`);
}
