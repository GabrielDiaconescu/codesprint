/**
 * `npm run store:screenshots` — the store screenshots, from the real app (Phase 23).
 *
 * On the development build and the local database, the way the E2E suite runs: for every
 * listing language and both themes, the database is reset to the showcase learner
 * (fixtures.ts), a generated Maestro flow walks Home → a lesson → a right answer → Learn →
 * Progress and captures each, and compose.ts turns the captures into store images.
 *
 * Usage: npm run store:screenshots [-- --compose-only] [-- --only ro/dark]
 *
 * `--only` retakes one language and theme and keeps the other captures — an emulator under
 * load occasionally turns a tap into a long press, and one retake beats four.
 */

const GENERATED_FLOW = join(ROOT, 'store', 'generated', 'capture.yaml');
const OUTPUT_DIR = join(ROOT, 'store', 'generated', 'maestro');

/**
 * Scroll to an element far down a long screen and tap it. The E2E steps allow 20 s, which a
 * long lesson page on a busy emulator has outrun; a screenshot run can afford to wait.
 */
const scrollAndTap = (id: string) => [
  {
    scrollUntilVisible: {
      element: { id },
      direction: 'DOWN',
      timeout: 60_000,
      visibilityPercentage: 100,
      centerElement: true,
    },
  },
  { tapOn: { id } },
];

const screenshot = (id: ScreenshotId) => [
  { waitForAnimationToEnd: { timeout: 5000 } },
  { takeScreenshot: id },
];

/** The walk through the app, captured in SCREENSHOT_IDS order. */
export const captureFlow = (courses = loadCourses()): string => {
  const { lesson, question } = pickShowcase(courses);
  const firstModule = courses[0]?.modules[0]?.data.slug;
  if (!firstModule) throw new Error('no module to wait for in Learn');

  const commands: (Command | Record<string, unknown>)[] = [
    { runFlow: '../../e2e/subflows/launch.yaml' },
    {
      runFlow: {
        file: '../../e2e/subflows/sign-in.yaml',
        env: { EMAIL: SHOWCASE_ACCOUNT.email, PASSWORD: '${DEV_PASSWORD}' },
      },
    },
    // The emulator's own theme is light (capture.ts sets it); one tap on Home switches.
    {
      runFlow: {
        when: { true: "${THEME == 'dark'}" },
        commands: [{ tapOn: { id: 'home-theme' } }],
      },
    },
    {
      runFlow: {
        when: { true: "${LANGUAGE == 'ro'}" },
        commands: [{ tapOn: { id: 'home-language' } }],
      },
    },
    waitFor('home-continue'),
    ...screenshot('home'),

    // "Continue" opens the showcase lesson on its first page: explanation and code. Captured
    // from the top — the page's own Continue is below the fold on a long explanation.
    ...tap('home-continue'),
    waitFor('lesson-scroll'),
    ...screenshot('lesson'),

    // Its first question, answered right, with the explanation showing.
    ...scrollAndTap('lesson-continue'),
    ...checkAnswer(question, 'correct'),
    ...screenshot('feedback'),

    // Back to Home — the lesson has no leave confirmation; a first Back may only close the
    // keyboard of a typed answer.
    {
      repeat: {
        while: { notVisible: { id: 'player-card' } },
        times: 3,
        commands: [{ pressKey: 'back' }, { waitForAnimationToEnd: { timeout: 3000 } }],
      },
    },
    // A tab tapped while Back is still settling can go unnoticed: tap until Learn is there.
    {
      repeat: {
        while: { notVisible: { id: `module-${firstModule}` } },
        times: 3,
        commands: [{ tapOn: { id: 'tab-learn' } }, { waitForAnimationToEnd: { timeout: 3000 } }],
      },
    },
    waitFor(`module-${firstModule}`),
    ...screenshot('learn'),

    { tapOn: { id: 'tab-home' } },
    // The last button on Home, below the practice card.
    ...scrollAndTap('home-progress'),
    waitFor('level-card'),
    ...screenshot('progress'),
  ];

  return (
    `# GENERATED by scripts/store/capture.ts from content/ — do not edit.\n` +
    `# Showcase lesson: ${lesson.slug}\n` +
    `appId: \${APP_ID}\n---\n${stringify(commands)}`
  );
};

/** Where Android draws its bars on this device, so compose.ts can cut them off. */
const measureDevice = (): DeviceFrame => {
  const size = /(\d+)x(\d+)/.exec(adb(['shell', 'wm', 'size']));
  const windows = adb(['shell', 'dumpsys', 'window']);
  const bar = (type: string) => {
    const match = new RegExp(`type=${type}[^}]*?frame=\\[\\d+,(\\d+)\\]\\[\\d+,(\\d+)\\]`).exec(
      windows,
    );
    return match ? Number(match[2]) - Number(match[1]) : null;
  };
  const statusBar = bar('statusBars');
  const navigationBar = bar('navigationBars');
  if (!size || statusBar === null || navigationBar === null) {
    return fail('Could not measure the screen and its system bars (adb shell dumpsys window).');
  }
  return { width: Number(size[1]), height: Number(size[2]), statusBar, navigationBar };
};

/** Maestro writes into its own output folder; the newest file by each name is this run's. */
const collect = (dir: string, locale: string, theme: 'light' | 'dark') => {
  const found = new Map<string, { path: string; time: number }>();
  const walk = (at: string) => {
    for (const entry of readdirSync(at, { withFileTypes: true })) {
      const path = join(at, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.name.endsWith('.png')) {
        const id = entry.name.slice(0, -4);
        const time = statSync(path).mtimeMs;
        if ((found.get(id)?.time ?? 0) < time) found.set(id, { path, time });
      }
    }
  };
  walk(dir);

  for (const id of SCREENSHOT_IDS) {
    const shot = found.get(id);
    if (!shot) fail(`The ${locale} ${theme} run did not capture "${id}".`);
    const target = rawPath(locale, theme, id);
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(shot!.path, target);
  }
};

const main = async () => {
  if (process.argv.includes('--compose-only')) {
    console.log(`Composed ${composeAll().length} images under store/screenshots/.`);
    return;
  }

  step('Checking the device, Maestro and local Supabase');
  checkDevice();
  const maestro = findMaestro();
  const publishableKey = localPublishableKey();
  const courses = loadCourses();
  const source = loadStoreSource();

  mkdirSync(dirname(GENERATED_FLOW), { recursive: true });
  writeFileSync(GENERATED_FLOW, captureFlow(courses));
  const fixtures = showcaseSql(courses);

  const onlyIndex = process.argv.indexOf('--only');
  const only = onlyIndex >= 0 ? process.argv[onlyIndex + 1] : undefined;
  if (!only) rmSync(RAW_DIR, { recursive: true, force: true });
  mkdirSync(RAW_DIR, { recursive: true });
  writeFileSync(join(RAW_DIR, 'device.json'), JSON.stringify(measureDevice(), null, 2));

  // Light system theme, so one tap on Home's toggle means dark; the app follows it otherwise.
  adb(['shell', 'cmd', 'uimode', 'night', 'no']);
  reversePorts();
  const metro = await startMetro(publishableKey);
  // `fail` exits the process, which skips `finally`: stop Metro on every way out.
  process.on('exit', () => stopMetro(metro));

  try {
    for (const listing of source.listings) {
      for (const theme of THEMES) {
        if (only && only !== `${listing.appleLocale}/${theme}`) continue;
        const label = `${listing.appleLocale}, ${theme}`;
        rmSync(join(RAW_DIR, listing.appleLocale, theme), { recursive: true, force: true });
        // The same learner every time: a run's own answer must not show up in the next one.
        resetDatabase();
        applyLocalSql(fixtures, 'the screenshot learner');

        step(`Capturing ${label}`);
        rmSync(OUTPUT_DIR, { recursive: true, force: true });
        mkdirSync(OUTPUT_DIR, { recursive: true });
        const exitCode = runMaestro(maestro, [
          'test',
          '--no-ansi',
          '-e',
          `APP_ID=${APP_ID}`,
          '-e',
          `METRO_PORT=${METRO_PORT}`,
          '-e',
          `DEV_PASSWORD=${DEV_PASSWORD}`,
          '-e',
          `THEME=${theme}`,
          '-e',
          `LANGUAGE=${listing.i18n}`,
          // As the E2E runner does. Without a report format, Maestro prints every step live,
          // and here it died silently mid-step, twice, where the same subflow passes in E2E.
          '--format',
          'junit',
          '--output',
          join(OUTPUT_DIR, 'report.xml'),
          '--test-output-dir',
          OUTPUT_DIR,
          GENERATED_FLOW,
        ]);
        if (exitCode !== 0) {
          fail(`The ${label} capture failed (Maestro exit ${exitCode}) — see ${OUTPUT_DIR}.`);
        }
        collect(OUTPUT_DIR, listing.appleLocale, theme);
      }
    }
  } finally {
    stopMetro(metro);
  }

  step('Composing the store images');
  console.log(`\n✔ ${composeAll(source).length} images under store/screenshots/.`);
};

if (/store[\\/]capture/.test(process.argv[1] ?? '')) void main();
