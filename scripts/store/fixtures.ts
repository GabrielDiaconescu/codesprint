import type { LoadedCourse } from '../content/load';
import { DEV_USERS } from '../content/seed';
import type { ContentQuestion, LessonFile } from '../../src/lib/content/schema';

/**
 * The learner in the store screenshots (Phase 23): a few modules in, a week-long streak, the
 * next lesson waiting. LOCAL DATABASE ONLY — applied by `npm run store:screenshots` through
 * `docker exec`, like the E2E fixtures.
 *
 * Progress is made the way a learner makes it: every earlier lesson is played through the real
 * `submit_answer` and `complete_lesson`, so XP, level, achievements and the skill breakdown are
 * exactly what those lessons give. Only two things are set directly, because they cannot be
 * replayed in one sitting: the six earlier days of the streak, and the display name.
 */

export const SHOWCASE_ACCOUNT = (() => {
  const user = DEV_USERS.find((u) => u.email === 'premium@codesprint.test');
  if (!user) throw new Error('no seeded premium account');
  return user;
})();

/** The name in the Home greeting. Premium, so no lives row and no ads cover the screens. */
export const SHOWCASE_NAME = 'Maya';

/** Days in a row, today included. */
export const SHOWCASE_STREAK = 7;

/** Question types whose page reads well at a glance: code, then choices. */
const SHOWCASE_TYPES = new Set(['multiple_choice', 'predict_output']);

/** From this module on, the learner has visibly got somewhere. */
const FIRST_SHOWCASE_MODULE = 4;

interface Showcase {
  lesson: LessonFile;
  /** Every lesson before it, in course order: the ones the learner has finished. */
  finished: LessonFile[];
  /** The lesson's first question: answered right on camera. */
  question: ContentQuestion;
}

/**
 * The lesson "Continue" leads to in the screenshots: the first one, from module 4 on, whose
 * opening page shows code and whose first question is one of the showcase types.
 */
export const pickShowcase = (courses: LoadedCourse[]): Showcase => {
  const lessons = courses.flatMap((course) =>
    course.modules.flatMap((module, moduleIndex) =>
      module.lessons.map((lesson) => ({ lesson: lesson.data, moduleNumber: moduleIndex + 1 })),
    ),
  );

  const index = lessons.findIndex(({ lesson, moduleNumber }) => {
    if (moduleNumber < FIRST_SHOWCASE_MODULE) return false;
    const firstQuestion = lesson.blocks.findIndex((block) => block.type === 'question');
    const opening = lesson.blocks.slice(0, Math.max(firstQuestion, 0));
    const question = lesson.blocks[firstQuestion];
    return (
      opening.some((block) => block.type === 'code') &&
      question?.type === 'question' &&
      SHOWCASE_TYPES.has(question.question.type)
    );
  });

  const found = lessons[index];
  const first = found?.lesson.blocks.find((block) => block.type === 'question');
  if (!found || first?.type !== 'question') throw new Error('no lesson fits the screenshots');

  return {
    lesson: found.lesson,
    finished: lessons.slice(0, index).map(({ lesson }) => lesson),
    question: first.question,
  };
};

const literal = (value: string): string => `'${value.replace(/'/g, "''")}'`;

export const showcaseSql = (courses: LoadedCourse[]): string => {
  const { finished } = pickShowcase(courses);
  const id = literal(SHOWCASE_ACCOUNT.id);

  return `-- GENERATED by scripts/store/fixtures.ts for the store screenshots. LOCAL DATABASE ONLY.
begin;

update public.profiles
set display_name = ${literal(SHOWCASE_NAME)},
    experience_level = 'beginner',
    motivation = 'career',
    daily_goal_minutes = 10,
    onboarding_completed_at = now()
where id = ${id};

-- ${finished.length} lessons, played through the real functions, as the learner.
do $$
declare
  v_lesson uuid;
  r record;
begin
  perform set_config(
    'request.jwt.claims',
    json_build_object('sub', ${id}, 'role', 'authenticated')::text,
    true
  );

  foreach v_lesson in array array[${finished.map((l) => literal(l.id)).join(', ')}]::uuid[]
  loop
    -- The answer limit (60 a minute) is for people; a replay of weeks of lessons is not one.
    -- Emptying this learner's counter between lessons keeps every answer going through
    -- submit_answer as usual.
    delete from public.rate_limit_counters where user_id = ${id};

    for r in
      select q.id, k.answer
      from public.questions q
      join public.question_answer_keys k on k.question_id = q.id
      where q.lesson_id = v_lesson
      order by q.order_index
    loop
      perform public.submit_answer(r.id, r.answer, 'lesson');
    end loop;

    perform public.complete_lesson(v_lesson);
  end loop;
end;
$$;

-- The six days before today, so the streak reads ${SHOWCASE_STREAK}. Replaying them would take a week.
insert into public.user_daily_activity (user_id, local_date, lessons_completed, questions_answered, xp_earned, qualified)
select ${id}, today.d - n, 1, 5, 60, true
from (select max(local_date) as d from public.user_daily_activity where user_id = ${id}) as today,
     generate_series(1, ${SHOWCASE_STREAK - 1}) as n
on conflict (user_id, local_date) do nothing;

update public.user_stats
set current_streak = ${SHOWCASE_STREAK},
    longest_streak = greatest(longest_streak, ${SHOWCASE_STREAK})
where user_id = ${id};

-- What a streak that long has earned, awarded by the real achievement engine — otherwise the
-- first answer on camera unlocks it, and Home and Progress show different totals.
select public.evaluate_achievements(${id}, array['streak_days']);

commit;
`;
};
